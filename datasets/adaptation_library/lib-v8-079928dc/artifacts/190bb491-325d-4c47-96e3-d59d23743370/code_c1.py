def crear_lista_de_notas():
    """Crea una lista con 4 notas de estudiantes."""
    notas = []  # Inicializa una lista vacía
    notas.append(12)  # Agrega la primera nota
    notas.append(15)  # Agrega la segunda nota
    notas.append(18)  # Agrega la tercera nota
    notas.append(9)   # Agrega la cuarta nota
    return notas  # Devuelve la lista de notas
